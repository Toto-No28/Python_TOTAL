# Operadores de comparación
# == (igualdad)
# != (desigualdad)
# > (mayor que)
# < (menor que)
# >= (mayor o igual que)
# <= (menor o igual que)

# Ejemplos
print(10 == 10)
print(10 != 10)
print(10 > 10)
print(10 < 10)
print(10 >= 10)
print(10 <= 10)

print('-' * 50)

# También se hacen comparaciones con strings
print("hola" == "hola")
print("hola" != "hola")
print("hola" > "hola")
print("hola" < "hola")
print("hola" >= "hola")
print("hola" <= "hola")

# Es importante aclarar que los comparadores en strings son sensibles a mayúsculas y minúsculas
print("hola" == "Hola")
print("hola" != "Hola")
print("hola" > "Hola")
print("hola" < "Hola")
print("hola" >= "Hola")
print("hola" <= "Hola")
print("hola" <= "Hola".lower())


